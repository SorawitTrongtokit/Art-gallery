export function demoDrafts(imageId: string): Draft[] {
  const home: Home = {
    storyTitle: 'ความทรงจำแสนเรียบง่าย (และวิธีทำไข่เจียวในวัยเด็ก)',
    storyIntro: 'หากพูดถึงกลิ่นที่ทำให้เรานึกถึงบ้านและความเป็นเด็กได้เร็วที่สุด คงหนีไม่พ้นกลิ่นไข่เจียวทอดร้อน ๆ ที่ส่งกลิ่นหอมฟุ้งจากห้องครัวหลังเลิกเรียน นิทรรศการ Inner Child จึงอยากชวนทุกคนมาละเมียดละไมกับความทรงจำธรรมดาแต่แสนพิเศษ',
    steps: [
      { title: 'เตรียมวัตถุดิบ', text: 'ตอกไข่ไก่ลงในชาม ปรุงรสตามชอบ' },
      { title: 'ตีให้ขึ้นฟอง', text: 'ใช้ส้อมตีไข่ให้ไข่ขาวและไข่แดงเข้ากัน' },
      { title: 'ตั้งกระทะ', text: 'อุ่นน้ำมันในกระทะก่อนเทไข่ลงไป' },
      { title: 'ทอดจนเหลืองทอง', text: 'ทอดให้สุกทั้งสองด้าน แล้วเสิร์ฟคู่ข้าวสวย' },
    ],
    contactTitle: 'ติดต่อผู้จัดงาน',
    contactText: 'งานนิทรรศการศิลปะ ชั้นมัธยมศึกษาปีที่ 6 ปีการศึกษา 2569',
    contacts: [{ label: 'Instagram: @innerchild.exhibition', url: '' }, { label: 'Email: innerchild2569@school.ac.th', url: '' }],
    slides: slides.map(([tag, title, text]) => ({ tag, title, text, imageId, imageAlt: 'ภาพประกอบตัวอย่างนิทรรศการ' })),
  };
  const categoryDrafts: Draft[] = categories.map(({ code, enTitle, thTitle, symbol }, index) => ({
    kind: 'category', key: code, expected: null,
    data: { enTitle, thTitle, symbol, poem: categoryText[index][0], description: categoryText[index][1] },
  }));
  const artworks: Draft[] = Array.from({ length: 144 }, (_, index) => {
    const sequence = String(index + 1).padStart(3, '0');
    return {
      kind: 'artwork', key: 'IC-' + sequence, expected: null,
      data: {
        categoryCode: categories[index % categories.length].code, title: 'ผลงานตัวอย่าง ' + sequence,
        artist: 'ผู้สร้างตัวอย่าง ' + sequence, technique: 'สื่อผสม', type: 'งานศิลปะ',
        concept: 'ข้อมูลจำลองสำหรับทดสอบการแสดงผลงานและการเผยแพร่', imageId, imageAlt: 'ภาพประกอบสำหรับทดสอบ',
      },
    };
  });
  return [{ kind: 'home', key: 'home', expected: null, data: home }, ...categoryDrafts, ...artworks];
}
